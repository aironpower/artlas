export function t(lang: Lang, key: UIKey): string {
  return UI[lang][key] ?? UI[DEFAULT_LANG][key];
}

/** Formatea metros como '350 m' o '2,4 km' según el idioma. */
export function formatDistance(lang: Lang, meters: number): string {
  return meters < 1000
    ? `${Math.round(meters)} m`
    : `${new Intl.NumberFormat(lang, { maximumFractionDigits: 1 }).format(meters / 1000)} km`;
}

export function formatNumber(lang: Lang, value: number): string {
  return new Intl.NumberFormat(lang).format(value);
}
